#!/usr/bin/env bash
#
# Rebuilds vendor/harper-editor (Harper's editor interface) from a Harper release.
#
#   scripts/update-harper.sh            # rebuild at the tag recorded below
#   scripts/update-harper.sh v2.13.0    # move to a newer release
#
# Needs: bash, git, Node 22+, pnpm 10 (`corepack enable` provides it). No Rust.
#
# How it works: Harper's editor lives in three small packages of its repository
# (harper-editor, lint-framework, components). They are built with Harper's own
# build scripts. The grammar engine itself (Rust compiled to WebAssembly) is not
# rebuilt here; the published `harper.js` npm package pinned in package.json is
# dropped in instead. So the engine version is whatever package.json says, and
# this script only controls the version of the interface.
#
# If a newer interface needs a newer engine, the lint-framework build fails with
# type errors. Bump "harper.js" in package.json first (npm publishes it less
# often than GitHub tags appear), or stay on the previous tag.

set -euo pipefail

TAG="${1:-v2.13.0}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${HARPER_WORKDIR:-$ROOT/.harper-src}"
ENGINE="$(node -p "require('$ROOT/package.json').dependencies['harper.js']")"

echo "==> Harper interface $TAG, engine harper.js@$ENGINE"

# 1. Harper's source at that tag.
if [ -d "$WORK/.git" ]; then
	git -C "$WORK" fetch --quiet --depth 1 origin tag "$TAG"
	git -C "$WORK" checkout --quiet --force "$TAG"
	git -C "$WORK" clean --quiet -fd -- packages/harper-editor packages/lint-framework packages/components
else
	git clone --quiet --depth 1 --branch "$TAG" https://github.com/Automattic/harper.git "$WORK"
fi

# 2. Stand in for the Rust-built parts with the published engine.
mkdir -p "$WORK/harper-wasm/pkg"
printf '{"name":"harper-wasm","version":"0.0.0","type":"module"}\n' > "$WORK/harper-wasm/pkg/package.json"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
(cd "$TMP" && npm pack --silent "harper.js@$ENGINE" > /dev/null && tar xzf harper.js-*.tgz)
rm -rf "$WORK/packages/harper.js/dist"
cp -r "$TMP/package/dist" "$WORK/packages/harper.js/dist"

# 3. The small changes this app needs (see patches/harper-editor.patch).
git -C "$WORK" apply --whitespace=nowarn "$ROOT/patches/harper-editor.patch"

# 4. Build the three packages the way Harper's own justfile does.
(cd "$WORK" && pnpm install --filter 'harper-editor...' --engine-strict=false --frozen-lockfile --silent)
for package in lint-framework components harper-editor; do
	echo "==> building $package"
	(cd "$WORK/packages/$package" && pnpm --silent build > /dev/null)
done

# 5. Copy the result in, runtime files only.
DEST="$ROOT/vendor/harper-editor"
rm -rf "$DEST/dist"
mkdir -p "$DEST"
cp -r "$WORK/packages/harper-editor/dist" "$DEST/dist"
find "$DEST/dist" -name '*.d.ts' -delete
cp "$WORK/LICENSE" "$DEST/LICENSE"

# 6. Record the licenses of the libraries Harper's build folded into that bundle
#    (the editor widget, the popup renderer, icons...). A dry-run build lists every
#    source file that went in; scripts/notices.mjs turns that into license texts.
echo "==> collecting license notices"
for package in lint-framework harper-editor; do
	cat > "$WORK/packages/$package/vite.modules.config.mjs" <<'CONFIG'
import { writeFileSync } from 'node:fs';
import { mergeConfig } from 'vite';
import base from './vite.config.ts';

const listModules = {
	name: 'list-modules',
	generateBundle(_, bundle) {
		const ids = new Set();
		for (const chunk of Object.values(bundle)) {
			if (chunk.type === 'chunk') {
				for (const id of Object.keys(chunk.modules)) ids.add(id);
			}
		}
		writeFileSync(process.env.MODULES_OUT, JSON.stringify([...ids]));
	},
};

export default mergeConfig(base, { build: { write: false }, plugins: [listModules] });
CONFIG
	(cd "$WORK/packages/$package" && MODULES_OUT="$TMP/$package.json" pnpm exec vite build -l error --config vite.modules.config.mjs > /dev/null)
	rm "$WORK/packages/$package/vite.modules.config.mjs"
done

# The stylesheet is generated by Tailwind (with the Flowbite plugin) rather than bundled
# from files, so name those two directly.
node -e '
	const { createRequire } = require("node:module");
	const fs = require("node:fs");
	const [work, out] = process.argv.slice(1);
	const from = (pkg, name) => createRequire(work + "/packages/" + pkg + "/package.json").resolve(name + "/package.json");
	fs.writeFileSync(out, JSON.stringify([from("harper-editor", "tailwindcss"), from("components", "flowbite")]));
' "$WORK" "$TMP/styles.json"

node "$ROOT/scripts/notices.mjs" "$DEST/THIRD-PARTY-NOTICES.txt" "$TMP/lint-framework.json" "$TMP/harper-editor.json" "$TMP/styles.json"

cat > "$DEST/package.json" <<JSON
{
	"name": "harper-editor",
	"version": "${TAG#v}",
	"license": "Apache-2.0",
	"description": "Prebuilt copy of packages/harper-editor from Automattic/harper ($TAG) with patches/harper-editor.patch applied. Regenerate with scripts/update-harper.sh.",
	"type": "module",
	"sideEffects": ["**/*.css"],
	"exports": {
		".": {
			"svelte": "./dist/index.js",
			"import": "./dist/index.js",
			"default": "./dist/index.js"
		},
		"./style.css": "./dist/harper-editor.css"
	},
	"peerDependencies": {
		"harper.js": "^2.0.0",
		"svelte": "^5.0.0"
	}
}
JSON

# The compiled components must run on the same Svelte version they were compiled with.
SVELTE="$(node -p "require(require.resolve('svelte/package.json', { paths: ['$WORK/packages/harper-editor'] })).version")"
echo "==> done. Harper compiled these components with svelte@$SVELTE;"
echo "    package.json here pins svelte@$(node -p "require('$ROOT/package.json').dependencies.svelte"). Keep the two equal, then: npm install && npm run build"
